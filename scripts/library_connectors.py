"""Board connectors: screw terminal blocks, pin headers (the male side, which a female socket plugs onto), female
(socket) headers, JST XH and two-row headers. Imported by gen-library.py, which writes them to connectors.json.

Every connector is a box with its pins in the order of the footprint. A 2-pin connector has "+" and "-" pins, so
the + pad is the square one on the board; the others are numbered, pin 1 square. The footprints are generated by
core/pcb/footprints.ts from the pole count (TB508_n, TB350_n, FHDR_n, JSTXH_n, HDR2Xn) or are the plain pin header
SIP_n.
"""


def build(h):
    txt, part, box = h["txt"], h["part"], h["box"]
    out = {"connectors.json": []}

    def names(n):
        return ["+", "-"] if n == 2 else [str(i) for i in range(1, n + 1)]

    def add(id, en, tr, n, fp, title, left=None, right=None):
        pins = names(n)
        symbol = box(left if left is not None else pins, right if right is not None else [], title)
        spec = part(id, txt(en, tr), "connector", "J", symbol, [], footprint=fp)
        if left is not None:
            spec["padMap"] = [str(i) for i in range(1, n + 1)]
        out["connectors.json"].append(spec)

    for n in (2, 3, 4, 5, 6, 8):
        add(f"term-508-{n}", f"Screw terminal block {n} poles (5.08 mm)", f"Vidalı klemens {n} kutuplu (5,08 mm)", n, f"TB508_{n}", f"TERM {n}")
    for n in (2, 3, 4, 6):
        add(f"term-350-{n}", f"Screw terminal block {n} poles (3.5 mm)", f"Vidalı klemens {n} kutuplu (3,5 mm)", n, f"TB350_{n}", f"TERM {n}")
    for n in range(2, 11):
        add(f"hdr-m-{n}", f"Pin header {n} pins, male (2.54 mm, takes a female socket)", f"Pin header {n} pin, erkek (2,54 mm, dişi soket takılır)", n, f"SIP_{n}", f"HDR {n}")
    for n in range(2, 11):
        add(f"hdr-f-{n}", f"Female header {n} pins (socket, 2.54 mm)", f"Dişi header {n} pin (soket, 2,54 mm)", n, f"FHDR_{n}", f"SOCKET {n}")
    for n in range(2, 13):
        add(f"plug-508-{n}", f"Pluggable terminal block {n} poles, male header (5.08 mm, takes the screw plug)", f"Geçmeli klemens {n} kutuplu, erkek (5,08 mm, vidalı fiş takılır)", n, f"PLUG508_{n}", f"PLUG {n}")
    for n in (2, 3, 4, 5, 6):
        add(f"jst-xh-{n}", f"JST XH connector {n} pins (2.5 mm)", f"JST XH konnektör {n} pin (2,5 mm)", n, f"JSTXH_{n}", f"JST XH {n}")
    for rows in (3, 4, 5):
        total = rows * 2
        add(f"hdr2-m-{total}", f"Pin header 2x{rows}, male ({total} pins, 2.54 mm)", f"Pin header 2x{rows}, erkek ({total} pin, 2,54 mm)", total, f"HDR2X{rows}", f"HDR 2x{rows}", [str(i) for i in range(1, total + 1, 2)], [str(i) for i in range(2, total + 1, 2)])

    return out
