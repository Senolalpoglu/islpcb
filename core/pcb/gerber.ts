// Fabrication output: Gerber RS-274X (copper, solder mask, silkscreen, solder paste, board outline) and an Excellon drill file.
// Coordinates are millimetres with the y axis flipped, so the files look the same in a viewer as on screen.

import { footprintById } from './footprints';
import { textStrokes } from './font';
import { polarityMarks } from './silk';
import { analyzePour, deadIslandRuns, pourContacts, pourCutouts, pourOutline, type Cutout } from './pour';
import type { AbsPad, Layer, PcbDoc, Pt } from './types';

export interface OutputFile {
  name: string;
  content: string;
}

const MASK_MARGIN = 0.05; // solder mask opening grows by this much around a pad
const SILK_WIDTH = 0.15;
const OUTLINE_WIDTH = 0.1;
const REF_HEIGHT = 1.0; // reference designator letters, mm
const SCALE = 1e6; // format 4.6: six decimals

class Layerfile {
  private readonly apertures = new Map<string, number>();
  private readonly body: string[] = [];
  private current = -1;

  constructor(
    private readonly title: string,
    private readonly fn: string,
    private readonly bounds: { y: number; h: number; x: number },
  ) {}

  private num(mm: number): string {
    return String(Math.round(mm * SCALE));
  }

  private x(v: number): string {
    return this.num(v - this.bounds.x);
  }

  private y(v: number): string {
    return this.num(this.bounds.h - (v - this.bounds.y));
  }

  /** Returns the D-code of an aperture, defining it on first use. */
  private aperture(def: string): number {
    let d = this.apertures.get(def);
    if (d === undefined) {
      d = 10 + this.apertures.size;
      this.apertures.set(def, d);
    }
    return d;
  }

  private select(def: string): void {
    const d = this.aperture(def);
    if (d !== this.current) {
      this.body.push(`D${d}*`);
      this.current = d;
    }
  }

  flashRound(p: Pt, dia: number): void {
    this.select(`C,${dia.toFixed(6)}`);
    this.body.push(`X${this.x(p.x)}Y${this.y(p.y)}D03*`);
  }

  flashRect(p: Pt, w: number, h: number): void {
    this.select(`R,${w.toFixed(6)}X${h.toFixed(6)}`);
    this.body.push(`X${this.x(p.x)}Y${this.y(p.y)}D03*`);
  }

  flashOval(p: Pt, w: number, h: number): void {
    this.select(`O,${w.toFixed(6)}X${h.toFixed(6)}`);
    this.body.push(`X${this.x(p.x)}Y${this.y(p.y)}D03*`);
  }

  /** A polyline drawn with a round pen of the given width. */
  stroke(pts: Pt[], width: number): void {
    if (pts.length < 2) return;
    this.select(`C,${width.toFixed(6)}`);
    this.body.push(`X${this.x(pts[0].x)}Y${this.y(pts[0].y)}D02*`);
    for (let i = 1; i < pts.length; i++) this.body.push(`X${this.x(pts[i].x)}Y${this.y(pts[i].y)}D01*`);
  }

  /** A filled polygon (a copper pour). */
  region(pts: Pt[]): void {
    if (pts.length < 3) return;
    this.body.push('G36*', `X${this.x(pts[0].x)}Y${this.y(pts[0].y)}D02*`);
    for (let i = 1; i < pts.length; i++) this.body.push(`X${this.x(pts[i].x)}Y${this.y(pts[i].y)}D01*`);
    this.body.push('G37*');
  }

  /** Dark polarity draws copper, clear polarity erases what is under it. */
  polarity(clear: boolean): void {
    this.body.push(clear ? '%LPC*%' : '%LPD*%');
  }

  toString(): string {
    const defs = [...this.apertures].map(([def, d]) => `%ADD${d}${def}*%`);
    return [
      `G04 ${this.title}*`,
      'G04 Generated by ISL PCB*',
      `%TF.FileFunction,${this.fn}*%`,
      '%FSLAX46Y46*%',
      '%MOMM*%',
      '%LPD*%',
      ...defs,
      'G01*',
      ...this.body,
      'M02*',
      '',
    ].join('\n');
  }
}

function flashCutout(file: Layerfile, c: Cutout): void {
  if (c.kind === 'round') file.flashRound(c.c, c.d);
  else if (c.kind === 'rect') file.flashRect(c.c, c.w, c.h);
  else if (c.kind === 'oval') file.flashOval(c.c, c.w, c.h);
  else file.stroke(c.pts, c.width);
}

function padShape(file: Layerfile, p: AbsPad, grow: number): void {
  if (p.shape === 'round') file.flashRound(p, p.w + grow);
  else if (p.shape === 'rect') file.flashRect(p, p.w + grow, p.h + grow);
  else file.flashOval(p, p.w + grow, p.h + grow);
}

const rectOutline = (cx: number, cy: number, w: number, h: number): Pt[] => [
  { x: cx - w / 2, y: cy - h / 2 },
  { x: cx + w / 2, y: cy - h / 2 },
  { x: cx + w / 2, y: cy + h / 2 },
  { x: cx - w / 2, y: cy + h / 2 },
  { x: cx - w / 2, y: cy - h / 2 },
];

/**
 * All fabrication files for a board, the way EasyEDA writes them: copper, solder mask, silkscreen and solder paste for
 * both sides, the board outline and the drill file. `name` prefixes the file names; `refs` (part id -> "R1") are
 * printed on the top silkscreen beside each part.
 */
export function exportFabrication(pcb: PcbDoc, pads: AbsPad[], name: string, refs?: Map<string, string>): OutputFile[] {
  const b = pcb.board;
  const make = (title: string, fn: string): Layerfile => new Layerfile(`${name} ${title}`, fn, { x: b.x, y: b.y, h: b.h });
  const paste: Record<Layer, Layerfile> = { top: make('top solder paste', 'Paste,Top'), bottom: make('bottom solder paste', 'Paste,Bot') };
  const copper: Record<Layer, Layerfile> = { top: make('top copper', 'Copper,L1,Top'), bottom: make('bottom copper', 'Copper,L2,Bot') };
  const mask: Record<Layer, Layerfile> = { top: make('top solder mask', 'Soldermask,Top'), bottom: make('bottom solder mask', 'Soldermask,Bot') };
  const silk: Record<Layer, Layerfile> = { top: make('top silkscreen', 'Legend,Top'), bottom: make('bottom silkscreen', 'Legend,Bot') };
  const outline = make('board outline', 'Profile,NP');
  const single = pcb.sides === 1;

  for (const l of ['top', 'bottom'] as Layer[]) {
    // Pours first: the plane, then a clear halo around the copper of other nets; the real copper goes on top below.
    for (const pour of pcb.pours ?? []) {
      if (pour.layer !== l || (single && l === 'top')) continue;
      copper[l].region(pourOutline(pcb));
      copper[l].polarity(true);
      for (const c of pourCutouts(pcb, pads, pour)) flashCutout(copper[l], c);
      // Pieces of the plane that no pad, via or track of its net touches would be floating copper: clear them too.
      const an = analyzePour(pcb, pads, pour);
      for (const run of deadIslandRuns(an, pourContacts(pcb, pads, pour, an))) {
        const hh = an.g / 2;
        copper[l].region([{ x: run.x0, y: run.y - hh }, { x: run.x1, y: run.y - hh }, { x: run.x1, y: run.y + hh }, { x: run.x0, y: run.y + hh }, { x: run.x0, y: run.y - hh }]);
      }
      copper[l].polarity(false);
    }
    for (const p of pads) {
      if (p.smd && l === 'bottom' && !single) continue;
      padShape(copper[l], p, 0);
      padShape(mask[l], p, 2 * MASK_MARGIN);
      if (p.smd && !single) padShape(paste[l], p, 0); // paste only where a part is soldered on the surface
    }
    for (const t of pcb.tracks) if (t.layer === l && !(single && l === 'top')) copper[l].stroke(t.pts, t.width);
    if (!single) for (const v of pcb.vias) copper[l].flashRound(v, v.dia); // vias are tented: no mask opening
  }

  // Silkscreen: the body outline of every footprint, on the top side.
  for (const fp of pcb.fps) {
    const def = footprintById(fp.footprint);
    if (!def) continue;
    const swap = fp.rot === 90 || fp.rot === 270;
    const bw = swap ? def.body.h : def.body.w;
    const bh = swap ? def.body.w : def.body.h;
    silk.top.stroke(rectOutline(fp.x, fp.y, bw, bh), SILK_WIDTH);
    const ref = refs?.get(fp.partId);
    if (ref) for (const s of textStrokes(ref, fp.x, fp.y - bh / 2 - REF_HEIGHT * 0.9, REF_HEIGHT)) silk.top.stroke(s, SILK_WIDTH);
  }

  for (const mark of polarityMarks(pcb, pads)) silk.top.stroke(mark, SILK_WIDTH);

  outline.stroke(rectOutline(b.x + b.w / 2, b.y + b.h / 2, b.w, b.h), OUTLINE_WIDTH);

  return [
    ...(single ? [] : [{ name: `${name}-F_Cu.gtl`, content: copper.top.toString() }]),
    { name: `${name}-B_Cu.gbl`, content: copper.bottom.toString() },
    { name: `${name}-F_Mask.gts`, content: mask.top.toString() },
    { name: `${name}-B_Mask.gbs`, content: mask.bottom.toString() },
    { name: `${name}-F_Silkscreen.gto`, content: silk.top.toString() },
    { name: `${name}-B_Silkscreen.gbo`, content: silk.bottom.toString() },
    { name: `${name}-Edge_Cuts.gm1`, content: outline.toString() },
    { name: `${name}-PTH.drl`, content: excellon(pcb, pads, name) },
    { name: `${name}-F_Paste.gtp`, content: paste.top.toString() },
    { name: `${name}-B_Paste.gbp`, content: paste.bottom.toString() },
  ];
}

/** Plated through-hole drill file: one tool per diameter, vias and component holes. */
export function excellon(pcb: PcbDoc, pads: AbsPad[], name: string): string {
  const b = pcb.board;
  const holes: Array<{ d: number; p: Pt }> = [];
  for (const p of pads) if (p.drill > 0) holes.push({ d: p.drill, p });
  for (const v of pcb.vias) holes.push({ d: v.drill, p: v });
  const diameters = [...new Set(holes.map((h) => h.d.toFixed(3)))].sort((a, c) => Number(a) - Number(c));
  const lines = ['M48', `; DRILL file for ${name}, generated by ISL PCB`, 'FMAT,2', 'METRIC,TZ', ...diameters.map((d, i) => `T${i + 1}C${d}`), '%'];
  diameters.forEach((d, i) => {
    lines.push(`T${i + 1}`);
    for (const h of holes.filter((x) => x.d.toFixed(3) === d)) lines.push(`X${(h.p.x - b.x).toFixed(3)}Y${(b.h - (h.p.y - b.y)).toFixed(3)}`);
  });
  lines.push('T0', 'M30', '');
  return lines.join('\n');
}
