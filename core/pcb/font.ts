/** The strokes of `text`, centred on (cx, cy), with letters `height` mm tall. */
export function textStrokes(text: string, cx: number, cy: number, height: number): Pt[][] {
  const s = height / 5;
  const advance = 4.6 * s;
  const chars = [...text.toUpperCase()].filter((c) => GLYPHS[c]);
  const left = cx - ((chars.length - 1) * advance + 3 * s) / 2;
  const out: Pt[][] = [];
  chars.forEach((c, i) => {
    for (const line of GLYPHS[c]) out.push(line.map(([gx, gy]) => ({ x: left + i * advance + gx * s, y: cy + (gy - 2.5) * s })));
  });
  return out;
}
